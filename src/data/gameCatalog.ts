export function computeHeroStats(
  loadout: HeroLoadout,
  level: number,
  upgrades: GearUpgrades = { weapon: 0, gun: 0, armor: 0 }
): ComputedStats {
  const cls = HERO_CLASSES.find((c) => c.id === loadout.classId) || HERO_CLASSES[0];
  const weapon = WEAPONS.find((w) => w.id === loadout.weaponId) || WEAPONS[0];
  const gun = GUNS.find((g) => g.id === loadout.gunId) || GUNS[0];
  const armor = ARMORS.find((a) => a.id === loadout.armorId) || ARMORS[0];
  const relic = RELICS.find((r) => r.id === loadout.relicId) || RELICS[0];
  const passive = PASSIVES.find((p) => p.id === loadout.passiveId) || PASSIVES[0];

  const levelBonusHp = (level - 1) * 16;
  const levelBonusAtk = (level - 1) * 2.2;
  const levelBonusDef = Math.floor((level - 1) * 0.9);

  const upgWeaponAtk = (upgrades?.weapon || 0) * 4;
  const upgGunDmg = (upgrades?.gun || 0) * 4;
  const upgArmorHp = (upgrades?.armor || 0) * 18;
  const upgArmorDef = (upgrades?.armor || 0) * 2;

  const speedBonusPct = passive.effect === 'fleetfoot' ? 1.16 : 1;
  const extraCdr = passive.effect === 'arcane' ? 20 : 0;

  return {
    maxHp: cls.baseHp + armor.hpBonus + relic.hpBonus + levelBonusHp + upgArmorHp,
    atk: Math.round(cls.baseAtk + weapon.atkBonus + relic.atkBonus + levelBonusAtk + upgWeaponAtk),
    gunDmg: Math.round(gun.damage + relic.atkBonus * 0.5 + (level - 1) * 1.4 + upgGunDmg),
    def: cls.baseDef + armor.defBonus + levelBonusDef + upgArmorDef + (passive.effect === 'ironskin' ? 6 : 0),
    speed: Math.round((cls.baseSpeed + armor.speedMod + relic.speedBonus) * speedBonusPct),
    critChance: Math.min(65, 5 + weapon.critBonus + relic.critBonus),
    cdr: Math.min(45, relic.cdrPercent + extraCdr),
    range: weapon.range,
    atkCooldownMs: weapon.cooldownMs,
  };
}
